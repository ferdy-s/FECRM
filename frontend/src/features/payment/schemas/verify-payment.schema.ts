import { z } from "zod";

//////////////////////////////////////////////////////
// ENUM
//////////////////////////////////////////////////////

export const paymentVerificationStatus = z.enum([
  "VERIFIED",
]);

//////////////////////////////////////////////////////
// SCHEMA
//////////////////////////////////////////////////////

export const verifyPaymentSchema = z.object({
  paymentId: z
    .string()
    .uuid("Invalid payment ID"),

  proofUrl: z
    .string()
    .trim()
    .url("Invalid proof URL"),

  status: paymentVerificationStatus,
});

//////////////////////////////////////////////////////
// TYPE
//////////////////////////////////////////////////////

export type VerifyPaymentFormValues =
  z.infer<typeof verifyPaymentSchema>;